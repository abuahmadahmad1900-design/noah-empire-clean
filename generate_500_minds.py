def generate_minds():
    minds_registry = []
    mind_id = 1
    for emp in emperors:
        templates = mind_templates.get(emp.name, [])
        for name in templates:
            mind_type = "rule"
            if "متنبئ" in name or "توقع" in name or "تحليل" in name:
                mind_type = "predictive"
            minds_registry.append({
                "id": mind_id,
                "emperor": emp.name,
                "name": name,
                "type": mind_type,
                "description": f"{name} - تابع لـ {emp.title}",
            })
            mind_id += 1
    return minds_registry

